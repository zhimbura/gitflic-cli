#!/usr/bin/env python3
"""Render every favicon for the docs site from a single source of truth.

The GitFlic-CLI mark is a red rounded square with a white "gf" wordmark. The
wordmark is emitted as *flattened vector paths* (not an SVG <text> element), so
the resulting icon.svg has **no font dependency**: headless rasterizers — most
importantly Yandex's favicon robot, which prefers the SVG — render the letters
identically without needing the original typeface installed. A <text>-based SVG
favicon can rasterize to a bare red square wherever the font is missing.

Outputs (overwritten in place):
  docs/public/_media/icon.svg            vector, font-independent (nav logo + favicon)
  docs/public/_media/favicon-16x16.png
  docs/public/_media/favicon-32x32.png
  docs/public/_media/favicon-192x192.png
  docs/public/_media/apple-touch-icon.png   180x180
  docs/public/favicon.ico                16/32/48/64/128 multi-size

Requirements: fonttools (pip), rsvg-convert (librsvg), magick (ImageMagick),
and Arial Bold on disk. Run from the repo root:

    python3 scripts/render-favicons.py
"""
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "docs" / "public"
MEDIA = PUBLIC / "_media"
FONT = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"

# Design constants — mirror the original hand-authored mark.
RED, WHITE = "#e8423a", "#ffffff"
BOX = 64                       # viewBox is 0 0 BOX BOX
TEXT = "gf"
FONT_SIZE = 28
BASELINE = 44                  # y of the text baseline
CENTER_X = BOX / 2             # wordmark is horizontally centered
LETTER_SPACING = -1            # px, between glyphs (matches original)

# Raster derivatives.
PNG_TARGETS = {
    MEDIA / "favicon-16x16.png": 16,
    MEDIA / "favicon-32x32.png": 32,
    MEDIA / "favicon-192x192.png": 192,
    MEDIA / "apple-touch-icon.png": 180,
}
ICO_SIZES = (16, 32, 48, 64, 128)


def build_svg() -> str:
    """Return the icon SVG with the wordmark flattened to <path> geometry."""
    font = TTFont(FONT)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]

    scale = FONT_SIZE / upm
    advances = [hmtx[cmap[ord(c)]][0] * scale for c in TEXT]
    total = sum(advances) + LETTER_SPACING * (len(TEXT) - 1)
    x = CENTER_X - total / 2

    subpaths = []
    for advance, char in zip(advances, TEXT):
        svg_pen = SVGPathPen(glyphs)
        # Font units are y-up with the baseline at 0; SVG is y-down. Bake the
        # scale/flip/translate into the coordinates so the emitted path needs no
        # transform attribute (maximally portable across minimal renderers).
        placed = TransformPen(svg_pen, (scale, 0, 0, -scale, x, BASELINE))
        glyphs[cmap[ord(char)]].draw(placed)
        subpaths.append(svg_pen.getCommands())
        x += advance + LETTER_SPACING

    d = " ".join(subpaths)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="0 0 {BOX} {BOX}" width="{BOX}" height="{BOX}">\n'
        f'  <!-- GitFlic-inspired mark: red rounded square + "gf" wordmark.\n'
        f'       The wordmark is flattened to vector path geometry (no font-\n'
        f'       dependent text element) so headless rasterizers render it\n'
        f'       identically. Generated by scripts/render-favicons.py. -->\n'
        f'  <rect x="2" y="2" width="60" height="60" rx="12" ry="12" fill="{RED}"/>\n'
        f'  <path fill="{WHITE}" d="{d}"/>\n'
        f'</svg>\n'
    )


def build_ico(entries: list[tuple[int, bytes]]) -> bytes:
    """Assemble a multi-size .ico that embeds each entry as a PNG blob.

    PNG-compressed ICO entries (supported by every modern browser and by
    Yandex's crawler) keep the file small — storing the 128px entry as raw BMP,
    as ImageMagick does by default, bloats it ~15x.
    """
    count = len(entries)
    directory = b""
    blobs = b""
    offset = 6 + 16 * count
    for size, data in entries:
        dim = 0 if size >= 256 else size  # 256 is encoded as 0 in ICO
        directory += struct.pack(
            "<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset
        )
        blobs += data
        offset += len(data)
    return struct.pack("<HHH", 0, 1, count) + directory + blobs


def render_png(svg: Path, out: Path, size: int) -> None:
    subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), str(svg), "-o", str(out)],
        check=True,
    )


def main() -> int:
    if shutil.which("rsvg-convert") is None:
        print("error: rsvg-convert not found on PATH", file=sys.stderr)
        return 1
    if not Path(FONT).exists():
        print(f"error: font not found: {FONT}", file=sys.stderr)
        return 1

    MEDIA.mkdir(parents=True, exist_ok=True)
    svg_path = MEDIA / "icon.svg"
    svg_path.write_text(build_svg())
    print(f"wrote {svg_path.relative_to(ROOT)}")

    for out, size in PNG_TARGETS.items():
        render_png(svg_path, out, size)
        print(f"wrote {out.relative_to(ROOT)} ({size}x{size})")

    with tempfile.TemporaryDirectory() as td:
        entries = []
        for size in ICO_SIZES:
            p = Path(td) / f"{size}.png"
            render_png(svg_path, p, size)
            entries.append((size, p.read_bytes()))
        ico = PUBLIC / "favicon.ico"
        ico.write_bytes(build_ico(entries))
        print(f"wrote {ico.relative_to(ROOT)} ({'/'.join(map(str, ICO_SIZES))})")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
